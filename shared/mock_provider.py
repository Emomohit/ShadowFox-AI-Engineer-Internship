class MockEmbeddingProvider:
    """
    Deterministic Hash-based Embedding Provider.
    Generates unit-normalized 384-dimensional dense vectors from text strings.
    Similar texts produce higher cosine similarities than dissimilar texts.
    """

    def __init__(self, dimension: int = 384):
        self.dimension = dimension

    def get_embedding(self, text: str) -> List[float]:
        """Convert text into a deterministic, normalized dense vector."""
        if not text:
            return [0.0] * self.dimension

        # Seed pseudo-random generator with sha256 hash of text words
        tokens = text.lower().split()
        vector = np.zeros(self.dimension, dtype=np.float32)

        for i, token in enumerate(tokens):
            h = int(hashlib.sha256(token.encode('utf-8')).hexdigest(), 16)
            idx = h % self.dimension
            sign = 1.0 if ((h >> 8) % 2 == 0) else -1.0
            weight = 1.0 / (1.0 + (i * 0.05))
            vector[idx] += sign * weight

        norm = np.linalg.norm(vector)
        if norm > 0:
            vector = vector / norm
        else:
            vector[0] = 1.0

        return vector.tolist()

    def get_embeddings(self, texts: List[str]) -> List[List[float]]:
        return [self.get_embedding(t) for t in texts]
